using Microsoft.AspNetCore.Mvc.Razor;
using Microsoft.EntityFrameworkCore;
using BogsyVideoStoreRS.Controllers;
using BogsyVideoStoreRS.Data;
using BogsyVideoStoreRS.Filters;
using BogsyVideoStoreRS.Services;

var builder = WebApplication.CreateBuilder(args);

// ?? Database ??????????????????????????????????????????????????????????????
builder.Services.AddDbContext<BvsDbContext>(options =>
    options.UseSqlServer(builder.Configuration.GetConnectionString("DefaultConnection")));

// ?? Session ???????????????????????????????????????????????????????????????
builder.Services.AddDistributedMemoryCache();
builder.Services.AddSession(options =>
{
    options.IdleTimeout        = TimeSpan.FromMinutes(60); // #9: reduced from 4 hours
    options.Cookie.HttpOnly    = true;
    options.Cookie.IsEssential = true;
});

// ?? Auth filter ???????????????????????????????????????????????????????????
builder.Services.AddScoped<SessionAuthFilter>(); // #3

// ?? Background service (overdue status updater) ???????????????????????????
builder.Services.AddHostedService<OverdueStatusService>(); // #7

// ?? MVC / Razor ???????????????????????????????????????????????????????????
builder.Services
    .AddControllersWithViews()
    .AddRazorOptions(options =>
    {
        options.ViewLocationFormats.Add("/BogsyVideoStoreRS/Views/{1}/{0}.cshtml");
        options.ViewLocationFormats.Add("/BogsyVideoStoreRS/Views/Shared/{0}.cshtml");
    });

var app = builder.Build();

// ?? Auto-migrate on startup ???????????????????????????????????????????????
using (var scope = app.Services.CreateScope())
{
    var db = scope.ServiceProvider.GetRequiredService<BvsDbContext>();
    db.Database.Migrate();
}

if (!app.Environment.IsDevelopment())
{
    app.UseExceptionHandler("/Home/Error");
    app.UseHsts();
}

app.UseHttpsRedirection();
app.UseStaticFiles();

app.UseRouting();

app.UseSession();
app.UseAuthorization();

app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");

app.Run();
